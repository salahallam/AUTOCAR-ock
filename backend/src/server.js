import 'dotenv/config';
import express from 'express';
import helmet from 'helmet';
import cors from 'cors';
import cookieParser from 'cookie-parser';
import rateLimit from 'express-rate-limit';
import { pool } from './db.js';
import publicRoutes from './routes/public.js';
import adminRoutes from './routes/admin.js';
if(!process.env.JWT_SECRET || process.env.JWT_SECRET.length<32) throw new Error('JWT_SECRET must contain at least 32 characters');
const app=express();
app.set('trust proxy',1);
app.use(helmet());
app.use(cors({origin:[process.env.FRONTEND_ORIGIN,process.env.ADMIN_ORIGIN].filter(Boolean),credentials:true}));
app.use(express.json({limit:'20kb'}));app.use(cookieParser());
app.use('/api',rateLimit({windowMs:15*60*1000,limit:300,standardHeaders:true,legacyHeaders:false}));
app.use('/api/admin/login',rateLimit({windowMs:15*60*1000,limit:10,standardHeaders:true,legacyHeaders:false,message:{error:'Trop de tentatives. Réessayez plus tard.'}}));
app.get('/api/health',async(_req,res)=>{try{await pool.query('SELECT 1');res.json({status:'ok',database:'connected'})}catch{res.status(503).json({status:'error',database:'unavailable'})}});
app.use('/api',publicRoutes);app.use('/api/admin',adminRoutes);
app.use((err,_req,res,_next)=>{console.error(err);res.status(500).json({error:'Erreur interne du serveur.'})});
const port=Number(process.env.PORT||4000);
app.listen(port,()=>console.log(`Ahmed Car Rent API listening on port ${port}`));
